export const StoreLocaleContext = createContext('en')

export function useStoreLocale() {
  const language = useContext(StoreLocaleContext) === 'ar' ? 'ar' : 'en'

  function t(message, values) {
    const text = language === 'ar' && Object.hasOwn(arabic, message) ? arabic[message] : message
    if (!values) return text
    return text.replace(/\{(\w+)\}/g, (placeholder, name) => values[name] ?? placeholder)
  }

  return { language, direction: language === 'ar' ? 'rtl' : 'ltr', t }
}
